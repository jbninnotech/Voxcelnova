
import mongoose from "mongoose";

// ======================================================
// ADDRESS SCHEMA
// ======================================================

const addressSchema = new mongoose.Schema(
  {
    // ====================================================
    // USER
    // ====================================================
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },

    // ====================================================
    // FULL NAME
    // ====================================================
    fullName: {
      type: String,
      required: true,
      trim: true,
    },

    // ====================================================
    // PHONE
    // ====================================================
    phone: {
      type: String,
      required: true,
      trim: true,
    },

    // ====================================================
    // ADDRESS LINE 1
    // ====================================================
    addressLine1: {
      type: String,
      required: true,
      trim: true,
    },

    // ====================================================
    // ADDRESS LINE 2
    // ====================================================
    addressLine2: {
      type: String,
      default: "",
      trim: true,
    },

    // ====================================================
    // LANDMARK
    // ====================================================
    landmark: {
      type: String,
      default: "",
      trim: true,
    },

    // ====================================================
    // CITY
    // ====================================================
    city: {
      type: String,
      required: true,
      trim: true,
    },

    // ====================================================
    // STATE
    // ====================================================
    state: {
      type: String,
      required: true,
      trim: true,
    },

    // ====================================================
    // POSTAL CODE
    // ====================================================
    postalCode: {
      type: String,
      required: true,
      trim: true,
    },

    // ====================================================
    // COUNTRY
    // ====================================================
    country: {
      type: String,
      default: "India",
      trim: true,
    },

    // ====================================================
    // ADDRESS TYPE
    // ====================================================
    // IMPORTANT:
    // Frontend sends "Office", so "Office" must be
    // included in the enum.
    // ====================================================
    addressType: {
      type: String,
      enum: ["Home", "Office", "Other"],
      default: "Home",
      required: true,
      trim: true,
    },

    // ====================================================
    // DEFAULT ADDRESS
    // ====================================================
    isDefault: {
      type: Boolean,
      default: false,
    },
  },

  // ======================================================
  // TIMESTAMPS
  // ======================================================
  {
    timestamps: true,
  }
);

// ======================================================
// INDEX
// ======================================================

addressSchema.index({
  user: 1,
  isDefault: 1,
});

// ======================================================
// MODEL
// ======================================================

const Address = mongoose.model("Address", addressSchema);

export default Address;

